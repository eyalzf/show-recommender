// Bundles the Worker for deployment.
//
// The Worker serves the API *and* the built frontend from a single script,
// because deployment goes through the Cloudflare Workers upload API (one
// module file, no separate static-assets upload). This script:
//   1. reads the Vite output in dist/
//   2. generates worker/src/dist-assets.ts — a map of URL path -> file body
//   3. bundles worker/src/index.ts (which imports that map) with esbuild
//      into worker/bundle.js, the file that gets uploaded.
//
// Run via `npm run build` (vite build runs first).
import { build } from 'esbuild';
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import { join, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const distDir = join(root, 'dist');

const TEXT_EXTS = new Set(['.html', '.css', '.js', '.mjs', '.json', '.svg', '.txt', '.xml', '.map']);

async function collect(dir, base = '') {
  const entries = [];
  for (const name of await readdir(dir)) {
    const full = join(dir, name);
    const rel = `${base}/${name}`;
    if ((await stat(full)).isDirectory()) {
      entries.push(...(await collect(full, rel)));
    } else {
      entries.push(rel);
    }
  }
  return entries;
}

const files = await collect(distDir);
const assets = {};
for (const rel of files) {
  const buf = await readFile(join(distDir, rel));
  const ext = extname(rel).toLowerCase();
  assets[rel] = TEXT_EXTS.has(ext)
    ? { encoding: 'utf8', body: buf.toString('utf8') }
    : { encoding: 'base64', body: buf.toString('base64') };
}

const generated = `// GENERATED by scripts/bundle-worker.mjs — do not edit by hand.
// Embedded copy of the Vite build output (dist/), served by the Worker.
export const DIST_ASSETS: Record<string, { encoding: 'utf8' | 'base64'; body: string }> = ${JSON.stringify(assets)};
`;
await writeFile(join(root, 'worker', 'src', 'dist-assets.ts'), generated);
console.log(`embedded ${files.length} dist file(s) into worker/src/dist-assets.ts`);

await build({
  entryPoints: [join(root, 'worker', 'src', 'index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  conditions: ['workerd', 'worker', 'browser', 'module', 'import', 'default'],
  minify: true,
  outfile: join(root, 'worker', 'bundle.js'),
});
console.log('worker bundle written to worker/bundle.js');
